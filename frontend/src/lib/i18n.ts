const EN_MONTHS = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December',
]

/** Localized "August 2026" (en) / "Tháng 8/2026" (vi) from a yyyy-mm string. */
export function localizedMonth(month: string, lang: Lang): string {
  const [y, m] = month.split('-')
  const mi = Number(m)
  if (lang === 'en') return `${EN_MONTHS[mi - 1] ?? m} ${y}`
  return `Tháng ${mi}/${y}`
}

