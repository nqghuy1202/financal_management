/** Localize a default category name; unknown (user-created) names pass through. */
export function localizedCategory(name: string, lang: Lang): string {
  if (lang === 'en') return DEFAULT_CATEGORY_EN[name] ?? name
  return name
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.vi[key] ?? key
  if (vars) {
    for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, String(vars[k]))
  }
  return s
}
